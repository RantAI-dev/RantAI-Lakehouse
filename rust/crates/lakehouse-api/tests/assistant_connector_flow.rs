//! AI-16 decision 1 (PR 1): measure the assistant building a connector end to
//! end, without changing any behaviour.
//!
//! # Why `POST /api/ai/tool` per step, not a mock-model chat
//!
//! The seam measured here is the one the model calls: each tool's registered
//! name and argument contract, dispatched through the exact same gate the
//! chat loop runs (`routes::ai::tool_call` -> `gate::decide` -> `run_tool`).
//! Driving one tool per request keeps every step's success or refusal visible
//! on its own, so a failure names the step that a real prompt would break at;
//! a mock-model round would hide a tool's own failure behind the round's
//! ordering. The three `AI-15` eval cases in `ops/ai_eval/dashboard_cases.json`
//! measure the model's orchestration of these same tools on staging's model.
//!
//! The source is the harness's own test `Postgres` (the one `common::spin_up`
//! migrates each test against), reached through a TLS-terminating loopback
//! proxy because a `PostgreSQL` dial requires TLS. No secret VALUE travels
//! through the chat: `create_connector` derives the `env:` reference from its
//! generated id, and a test-only resolver supplies the value to the source
//! probe. `run_ingest` is stopped at a mocked `Dagster` boundary; the Bronze
//! result asserted here is the saved spec's Bronze target plus the launch of
//! this connector's ingest job, which is what writes that table.

