/// Answers any derived `env:` connector reference with the test `Postgres`
/// password. The connector id is generated by `create_connector` at runtime,
/// so a fixed-name map (as in `connector_secret_rotate.rs`) cannot be built
/// before the app starts; ignoring the name is safe because this resolver
/// lives only inside this test binary.
struct PgPasswordResolver(String);

// Never derive `Debug`: the password is a secret and must not leak through a
// resolver's `Debug` output (the trait requires `Debug`).
impl std::fmt::Debug for PgPasswordResolver {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("PgPasswordResolver(<redacted>)")
    }
}

#[async_trait::async_trait]
impl DynSecretResolver for PgPasswordResolver {
    async fn resolve_dyn(&self, _secret_ref: &str) -> Result<SecretValue, SecretError> {
        Ok(SecretValue::new(self.0.clone()))
    }
}

/// Splits `postgres://user:pass@host:port/db` into its parts, as
/// `connector_repoint.rs` does. No URL-parsing crate for one substitution.
fn parse_postgres_url(url: &str) -> (String, String, String, u16) {
    let rest = url
        .strip_prefix("postgres://")
        .expect("database_url is a postgres:// URL");
    let (auth, host_port_db) = rest.split_once('@').expect("user:pass@host:port/db");
    let (user, password) = auth.split_once(':').expect("user:pass");
    let (host_port, _db) = host_port_db.split_once('/').expect("host:port/db");
    let (host, port) = host_port.rsplit_once(':').expect("host:port");
    (
        user.to_owned(),
        password.to_owned(),
        host.to_owned(),
        port.parse().expect("a numeric port"),
    )
}

/// A `Dagster` that says no run is going and answers one launch with a run id,
/// the same boundary `ingest_run.rs` uses for a successful ingest launch.
async fn dagster_for_ingest() -> MockServer {
    let server = MockServer::start().await;
    Mock::given(method("POST"))
        .and(path("/graphql"))
        .and(body_string_contains("runsOrError"))
        .respond_with(ResponseTemplate::new(200).set_body_json(json!({
            "data": { "runsOrError": { "__typename": "Runs", "results": [] } }
        })))
        .mount(&server)
        .await;
    Mock::given(method("POST"))
        .and(path("/graphql"))
        .and(body_string_contains("launchRun"))
        .respond_with(ResponseTemplate::new(200).set_body_json(json!({
            "data": { "launchRun": { "__typename": "LaunchRunSuccess",
                "run": { "runId": "run-bronze-orders" } } }
        })))
        .mount(&server)
        .await;
    server
}

/// Sends one tool call through the assistant's tool route and returns the
/// tool's own result. `step_name` appears in every assertion so a reader can
/// see exactly which step of the flow broke.
async fn step(app: &TestApp, cookie: &str, step_name: &str, tool: &str, args: Value) -> Value {
    let response = app
        .router
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/api/ai/tool")
                .header("content-type", "application/json")
                .header("cookie", cookie)
                .body(Body::from(
                    json!({ "tool": tool, "mode": "build", "args": args }).to_string(),
                ))
                .expect("build request"),
        )
        .await
        .expect("router never fails a request outright");
    assert_eq!(
        response.status(),
        StatusCode::OK,
        "step {step_name} ({tool}): unexpected HTTP status"
    );
    let bytes = to_bytes(response.into_body(), usize::MAX)
        .await
        .expect("read body");
    let body: Value = serde_json::from_slice(&bytes).expect("valid JSON");
    let result = body.get("result").cloned().unwrap_or_else(|| body.clone());
    assert!(
        result.get("error").is_none(),
        "step {step_name} ({tool}) failed: {body}"
    );
    result
}

/// Steps 2 to 5 of the flow, kept in one helper so the test body stays under
/// the crate's function-length limit. Every failure still names its step.
async fn set_spec_discover_and_run(app: &TestApp, cookie: &str, id: &str, dial: Value) {
    // 2. set_ingest_spec — a first save establishes the dial and the Bronze
    // target; sourceObjects is the argument the run below needs.
    step(
        app,
        cookie,
        "set_ingest_spec",
        "set_ingest_spec",
        json!({
            "id": id,
            "adapter": "sql",
            "ingestMode": "batch",
            "dial": dial,
            "sourceObjects": [{ "name": "public.orders", "target": "orders" }],
            "scheduleCron": "0 * * * *",
            "confirmed": true,
        }),
    )
    .await;

    // 3. discover_source — a real read of the test Postgres `public` schema.
    let discovered = step(
        app,
        cookie,
        "discover_source",
        "discover_source",
        json!({ "id": id, "schema": "public" }),
    )
    .await;
    assert_eq!(
        discovered["supported"], true,
        "step discover_source: {discovered}"
    );
    let objects = discovered["objects"]
        .as_array()
        .expect("step discover_source: an objects list");
    assert!(
        objects.iter().any(|o| o["name"] == json!("public.orders")),
        "step discover_source did not list public.orders: {discovered}"
    );

    // 4. get_ingest_spec — the spec the model would read before adding a table.
    let spec = step(
        app,
        cookie,
        "get_ingest_spec",
        "get_ingest_spec",
        json!({ "id": id }),
    )
    .await;
    assert_eq!(
        spec["sourceObjects"][0]["target"], "orders",
        "step get_ingest_spec: {spec}"
    );

    // 5. run_ingest — a confirmed launch through the assistant, stopped at the
    // mocked orchestrator boundary.
    let run = step(
        app,
        cookie,
        "run_ingest",
        "run_ingest",
        json!({ "id": id, "confirmed": true }),
    )
    .await;
    assert_eq!(run["runId"], "run-bronze-orders", "step run_ingest: {run}");
}

/// The Bronze result: the saved spec lands `public.orders` in Bronze table
/// `orders`, and the ingest job that writes it was launched for THIS connector
/// (the same assertion style `ingest_run.rs` uses for a launch).
async fn assert_bronze_result(app: &TestApp, id: &str, dagster: &MockServer) {
    let stored: Value = sqlx::query_scalar("SELECT source_objects FROM connector WHERE id = $1")
        .bind(id)
        .fetch_one(&app.pool)
        .await
        .expect("read the saved source objects");
    assert_eq!(stored[0]["target"], "orders", "Bronze target: {stored}");
    let launches: Vec<String> = dagster
        .received_requests()
        .await
        .expect("recorded requests")
        .iter()
        .map(|r| String::from_utf8_lossy(&r.body).to_string())
        .filter(|body| body.contains("launchRun"))
        .collect();
    assert_eq!(launches.len(), 1, "run_ingest launched once: {launches:?}");
    assert!(
        launches[0].contains(id),
        "the Bronze ingest launch did not name connector {id}: {}",
        launches[0]
    );
}

#[tokio::test]
async fn the_assistant_builds_a_postgres_connector_and_loads_orders_into_bronze() {
    let (user, password, host, port) = parse_postgres_url(&lakehouse_test_support::database_url());
    let proxy = common::tls_proxy::TlsProxy::start(&host, port).await;
    let dagster = dagster_for_ingest().await;

    let mut overrides = HashMap::new();
    overrides.insert(
        "CONNECTOR_PROBE_ALLOW_INTERNAL_HOSTS".to_owned(),
        "true".to_owned(),
    );
    overrides.insert(
        "DAGSTER_URL".to_owned(),
        format!("{}/graphql", dagster.uri()),
    );
    let app =
        spin_up_with_connector_secret_resolver(&overrides, Arc::new(PgPasswordResolver(password)))
            .await;
    let cookie = session_cookie_for_seeded_user(&app.pool, "bayu@meridian.example").await;
    let (database,): (String,) = sqlx::query_as("SELECT current_database()")
        .fetch_one(&app.pool)
        .await
        .expect("read the test database's own name");
    // The fresh per-test database holds only migrations, so the source table
    // the prompt names must be seeded before `discover_source` can list it.
    sqlx::query("CREATE TABLE public.orders (id text PRIMARY KEY, amount bigint)")
        .execute(&app.pool)
        .await
        .expect("seed the source table public.orders");

    // 1. create_connector — no secret value, only an env source and a key kind.
    let created = step(
        &app,
        &cookie,
        "create_connector",
        "create_connector",
        json!({
            "name": "assistant flow pg",
            "type": "PostgreSQL",
            "direction": "source",
            "host": "pg-src.test",
            "credential": { "source": "env", "primary": "password" },
            "environment": "production",
            "tenant": "meridian",
            "tenantId": "11111111-1111-4111-8111-000000000001",
            "confirmed": true,
        }),
    )
    .await;
    let id = created["id"]
        .as_str()
        .expect("step create_connector: the generated connector id")
        .to_owned();

    let dial = json!({
        "driver": "postgres",
        "host": "127.0.0.1",
        "port": proxy.port(),
        "database": database,
        "user": user,
    });

    set_spec_discover_and_run(&app, &cookie, &id, dial).await;
    assert_bronze_result(&app, &id, &dagster).await;
}
