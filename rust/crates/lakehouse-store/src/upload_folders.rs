//! Repository layer for `upload_folder` (`migrations/0112_upload_folders.sql`):
//! the folders that group the files on the Uploaded files tab (`DATA-35`).
//!
//! A folder is a grouping and nothing more (feature page `upload-folders.md`,
//! decision 1). Moving a file changes `file_upload.folder_id` and nothing a
//! pipeline, chart, saved query, lineage graph or search reads.
//!
//! # The rules live here, against the database (plan AD2)
//!
//! The console lists at most 100 files and shows the folders it was sent, so it
//! cannot be the judge of any of these. Each is checked in the store, inside one
//! transaction that holds a per-tenant advisory lock, so two requests of one
//! tenant cannot each pass a check the other is about to break (two moves that
//! together make a cycle, a create and a delete of the same parent):
//!
//! - **Depth** at most [`MAX_DEPTH`] levels (decision 3). A move counts the
//!   moved folder's own sub-folders too.
//! - **No cycle**: a folder cannot be moved into itself or into one of its
//!   descendants.
//! - **Names** are 1 to [`MAX_NAME_CHARS`] characters after trim, unique among
//!   the folders that share a parent, case-insensitively (decision 6).
//! - **Delete** only a folder with no file and no folder in it (decision 8).
//!
//! Each refusal is a [`FolderError`] variant; the route turns it into a fixed
//! sentence. Nothing here carries database text out (principle 4).
//!
//! # Tenant scope (`SEC-16`, decision 5)
//!
//! Every function takes the tenant and binds it in every statement, folders and
//! files alike. A folder id of another tenant is [`FolderError::NotFound`], the
//! same answer as an id that does not exist, so the answer says nothing about
//! which ids exist.

use serde::Serialize;
use sqlx::{FromRow, PgConnection};
use time::OffsetDateTime;
use uuid::Uuid;

use crate::uploads::ser_ts;
use crate::{PgPool, StoreError};

/// The deepest a folder may sit: three levels, the first being the top level
/// (feature page decision 3).
pub const MAX_DEPTH: i32 = 3;

/// The longest folder name, in characters, after trim. The migration's CHECK says
/// the same number.
pub const MAX_NAME_CHARS: usize = 100;

/// One folder with what is directly in it, as the tab lists it.
#[derive(Debug, Clone, FromRow, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UploadFolder {
    /// Opaque id, `uf-<uuid>`, generated by the API.
    pub id: String,
    /// The folder this one sits in; `None` at the top level.
    pub parent_id: Option<String>,
    /// The display name, trimmed.
    pub name: String,
    /// How many files are directly in this folder (not in its sub-folders).
    pub file_count: i64,
    /// How many folders are directly in this folder.
    pub child_count: i64,
    /// Display name of the principal who made it.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub created_by: Option<String>,
    /// When it was made.
    #[serde(serialize_with = "ser_ts")]
    pub created_at: OffsetDateTime,
    /// When it was last renamed or moved.
    #[serde(serialize_with = "ser_ts")]
    pub updated_at: OffsetDateTime,
}

/// Why a folder operation was refused, or that the store failed.
#[derive(Debug)]
pub enum FolderError {
    /// No such folder (or file) in the caller's tenant: unknown, or another
    /// tenant's, alike.
    NotFound,
    /// The name is empty after trim, or longer than [`MAX_NAME_CHARS`].
    NameInvalid,
    /// A sibling already has the name, compared case-insensitively.
    NameTaken,
    /// The folder would sit deeper than [`MAX_DEPTH`].
    TooDeep,
    /// A folder cannot be moved into itself or into one of its own folders.
    Cycle,
    /// The folder still holds a file or a folder.
    NotEmpty,
    /// The database failed; carries the store's own classified error.
    Store(StoreError),
}

impl From<StoreError> for FolderError {
    fn from(err: StoreError) -> Self {
        Self::Store(err)
    }
}

impl From<sqlx::Error> for FolderError {
    fn from(err: sqlx::Error) -> Self {
        Self::Store(StoreError::from(err))
    }
}

/// What a folder patch does to the parent. Three cases, so this is an enum and
/// not an `Option<Option<&str>>` (clippy `option_option`, PR #259 CI): "leave
/// it" and "move to the top level" must not be mistaken for each other, and the
/// names say which is which. The JSON route keeps its contract: `parentId`
/// absent is `Keep`, `null` is `Root`, text is `Under`.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum ParentChange<'a> {
    /// Leave the parent as it is.
    #[default]
    Keep,
    /// Move the folder to the top level.
    Root,
    /// Move the folder under this folder.
    Under(&'a str),
}

/// What to change on a folder: the name is left alone when `None`, the parent
/// when [`ParentChange::Keep`].
#[derive(Debug, Clone, Copy, Default)]
pub struct FolderPatch<'a> {
    /// The new name.
    pub name: Option<&'a str>,
    /// What to do with the parent.
    pub parent: ParentChange<'a>,
}

const SELECT_WITH_COUNTS: &str = "SELECT f.id, f.parent_id, f.name, \
     (SELECT count(*) FROM file_upload u \
       WHERE u.folder_id = f.id AND u.tenant_id = f.tenant_id) AS file_count, \
     (SELECT count(*) FROM upload_folder c \
       WHERE c.parent_id = f.id AND c.tenant_id = f.tenant_id) AS child_count, \
     f.created_by, f.created_at, f.updated_at \
     FROM upload_folder f";

/// The trimmed name, or [`FolderError::NameInvalid`].
fn checked_name(name: &str) -> Result<&str, FolderError> {
    let name = name.trim();
    let length = name.chars().count();
    if length == 0 || length > MAX_NAME_CHARS {
        return Err(FolderError::NameInvalid);
    }
    Ok(name)
}

/// Serialise this tenant's folder changes. The key is the tenant, so tenants
/// never wait for each other; the prefix keeps it apart from the other advisory
/// locks keyed on bare strings.
async fn lock_tenant(conn: &mut PgConnection, tenant_id: Uuid) -> Result<(), FolderError> {
    sqlx::query("SELECT pg_advisory_xact_lock(hashtext('upload_folder:' || $1::text))")
        .bind(tenant_id)
        .execute(conn)
        .await?;
    Ok(())
}

/// The level `id` sits on (1 at the top), or `None` when the tenant has no such
/// folder.
async fn depth_of(
    conn: &mut PgConnection,
    tenant_id: Uuid,
    id: &str,
) -> Result<Option<i32>, FolderError> {
    Ok(sqlx::query_scalar(
        "WITH RECURSIVE up AS ( \
             SELECT id, parent_id, 1 AS depth FROM upload_folder \
              WHERE id = $1 AND tenant_id = $2 \
             UNION ALL \
             SELECT f.id, f.parent_id, up.depth + 1 FROM upload_folder f \
               JOIN up ON f.id = up.parent_id WHERE f.tenant_id = $2) \
         SELECT max(depth) FROM up",
    )
    .bind(id)
    .bind(tenant_id)
    .fetch_one(conn)
    .await?)
}

/// How many levels the subtree of `id` has, `id` itself counting one, and whether
/// `candidate` is in it (`id` included).
async fn subtree_of(
    conn: &mut PgConnection,
    tenant_id: Uuid,
    id: &str,
    candidate: &str,
) -> Result<(i32, bool), FolderError> {
    let (height, contains): (Option<i32>, Option<bool>) = sqlx::query_as(
        "WITH RECURSIVE down AS ( \
             SELECT id, 1 AS depth FROM upload_folder \
              WHERE id = $1 AND tenant_id = $2 \
             UNION ALL \
             SELECT f.id, down.depth + 1 FROM upload_folder f \
               JOIN down ON f.parent_id = down.id WHERE f.tenant_id = $2) \
         SELECT max(depth), bool_or(id = $3) FROM down",
    )
    .bind(id)
    .bind(tenant_id)
    .bind(candidate)
    .fetch_one(conn)
    .await?;
    Ok((height.unwrap_or(0), contains.unwrap_or(false)))
}

/// `tenant_id`'s folders, with the counts of what is directly in each, by name.
///
/// # Errors
///
/// Returns [`StoreError::Database`] on a database failure.
pub async fn list(pool: &PgPool, tenant_id: Uuid) -> Result<Vec<UploadFolder>, StoreError> {
    let sql = format!("{SELECT_WITH_COUNTS} WHERE f.tenant_id = $1 ORDER BY lower(f.name), f.id");
    // safe: only the constant `SELECT_WITH_COUNTS` is formatted in; values are bound (SEC-41).
    Ok(sqlx::query_as(sqlx::AssertSqlSafe(sql.as_str()))
        .bind(tenant_id)
        .fetch_all(pool)
        .await?)
}

async fn one(
    conn: &mut PgConnection,
    tenant_id: Uuid,
    id: &str,
) -> Result<UploadFolder, FolderError> {
    let sql = format!("{SELECT_WITH_COUNTS} WHERE f.tenant_id = $1 AND f.id = $2");
    // safe: only the constant `SELECT_WITH_COUNTS` is formatted in; values are bound (SEC-41).
    sqlx::query_as(sqlx::AssertSqlSafe(sql.as_str()))
        .bind(tenant_id)
        .bind(id)
        .fetch_optional(conn)
        .await?
        .ok_or(FolderError::NotFound)
}

/// Whether `id` is a folder of `tenant_id`: the check the ingest makes before it
/// puts files in one.
///
/// # Errors
///
/// Returns [`StoreError::Database`] on a database failure.
pub async fn folder_in_tenant(
    pool: &PgPool,
    tenant_id: Uuid,
    id: &str,
) -> Result<bool, StoreError> {
    Ok(sqlx::query_scalar(
        "SELECT EXISTS (SELECT 1 FROM upload_folder WHERE id = $1 AND tenant_id = $2)",
    )
    .bind(id)
    .bind(tenant_id)
    .fetch_one(pool)
    .await?)
}

/// Make folder `id` named `name` under `parent_id` (`None`: the top level).
///
/// # Errors
///
/// [`FolderError::NameInvalid`], [`FolderError::NameTaken`] and
/// [`FolderError::TooDeep`] for the rules above; [`FolderError::NotFound`] when
/// `parent_id` is not a folder of the tenant; [`FolderError::Store`] on a
/// database failure.
pub async fn create(
    pool: &PgPool,
    tenant_id: Uuid,
    id: &str,
    parent_id: Option<&str>,
    name: &str,
    created_by: &str,
) -> Result<UploadFolder, FolderError> {
    let name = checked_name(name)?;
    let mut tx = pool.begin().await?;
    lock_tenant(&mut tx, tenant_id).await?;
    if let Some(parent) = parent_id {
        match depth_of(&mut tx, tenant_id, parent).await? {
            None => return Err(FolderError::NotFound),
            Some(depth) if depth >= MAX_DEPTH => return Err(FolderError::TooDeep),
            Some(_) => {}
        }
    }
    let inserted = sqlx::query(
        "INSERT INTO upload_folder (id, tenant_id, parent_id, name, created_by) \
         VALUES ($1, $2, $3, $4, $5)",
    )
    .bind(id)
    .bind(tenant_id)
    .bind(parent_id)
    .bind(name)
    .bind(created_by)
    .execute(&mut *tx)
    .await;
    if let Err(err) = inserted {
        return Err(match StoreError::from(err) {
            StoreError::Conflict => FolderError::NameTaken,
            other => FolderError::Store(other),
        });
    }
    let made = one(&mut tx, tenant_id, id).await?;
    tx.commit().await?;
    Ok(made)
}

/// Rename and/or move folder `id`.
///
/// # Errors
///
/// [`FolderError::NotFound`] when `id`, or the new parent, is not a folder of the
/// tenant; [`FolderError::NameInvalid`], [`FolderError::NameTaken`],
/// [`FolderError::Cycle`] and [`FolderError::TooDeep`] for the rules above;
/// [`FolderError::Store`] on a database failure.
pub async fn update(
    pool: &PgPool,
    tenant_id: Uuid,
    id: &str,
    patch: FolderPatch<'_>,
) -> Result<UploadFolder, FolderError> {
    let renamed = patch.name.map(checked_name).transpose()?;
    let mut tx = pool.begin().await?;
    lock_tenant(&mut tx, tenant_id).await?;
    let current: Option<(String, Option<String>)> = sqlx::query_as(
        "SELECT name, parent_id FROM upload_folder WHERE id = $1 AND tenant_id = $2 FOR UPDATE",
    )
    .bind(id)
    .bind(tenant_id)
    .fetch_optional(&mut *tx)
    .await?;
    let Some((current_name, current_parent)) = current else {
        return Err(FolderError::NotFound);
    };
    let parent = match patch.parent {
        ParentChange::Keep => current_parent.as_deref(),
        ParentChange::Root => None,
        ParentChange::Under(new_parent) => Some(new_parent),
    };
    if let ParentChange::Under(new_parent) = patch.parent {
        let Some(parent_depth) = depth_of(&mut tx, tenant_id, new_parent).await? else {
            return Err(FolderError::NotFound);
        };
        let (height, contains) = subtree_of(&mut tx, tenant_id, id, new_parent).await?;
        if contains {
            return Err(FolderError::Cycle);
        }
        if parent_depth + height > MAX_DEPTH {
            return Err(FolderError::TooDeep);
        }
    }
    let updated = sqlx::query(
        "UPDATE upload_folder SET name = $3, parent_id = $4, updated_at = now() \
         WHERE id = $1 AND tenant_id = $2",
    )
    .bind(id)
    .bind(tenant_id)
    .bind(renamed.unwrap_or(&current_name))
    .bind(parent)
    .execute(&mut *tx)
    .await;
    if let Err(err) = updated {
        return Err(match StoreError::from(err) {
            StoreError::Conflict => FolderError::NameTaken,
            other => FolderError::Store(other),
        });
    }
    let changed = one(&mut tx, tenant_id, id).await?;
    tx.commit().await?;
    Ok(changed)
}

/// Delete folder `id`, which must hold no file and no folder (decision 8).
///
/// # Errors
///
/// [`FolderError::NotFound`] when `id` is not a folder of the tenant;
/// [`FolderError::NotEmpty`] while it holds a file or a folder (also when one
/// arrives between the check and the delete: the foreign keys refuse it);
/// [`FolderError::Store`] on a database failure.
pub async fn delete(pool: &PgPool, tenant_id: Uuid, id: &str) -> Result<(), FolderError> {
    let mut tx = pool.begin().await?;
    lock_tenant(&mut tx, tenant_id).await?;
    let held: Option<bool> = sqlx::query_scalar(
        "SELECT EXISTS (SELECT 1 FROM file_upload WHERE folder_id = $1 AND tenant_id = $2) \
             OR EXISTS (SELECT 1 FROM upload_folder WHERE parent_id = $1 AND tenant_id = $2) \
         FROM upload_folder WHERE id = $1 AND tenant_id = $2",
    )
    .bind(id)
    .bind(tenant_id)
    .fetch_optional(&mut *tx)
    .await?;
    match held {
        None => return Err(FolderError::NotFound),
        Some(true) => return Err(FolderError::NotEmpty),
        Some(false) => {}
    }
    let deleted = sqlx::query("DELETE FROM upload_folder WHERE id = $1 AND tenant_id = $2")
        .bind(id)
        .bind(tenant_id)
        .execute(&mut *tx)
        .await;
    if let Err(err) = deleted {
        return Err(match StoreError::from(err) {
            StoreError::ForeignKeyViolation => FolderError::NotEmpty,
            other => FolderError::Store(other),
        });
    }
    tx.commit().await?;
    Ok(())
}

/// Move the uploads `upload_ids` into `folder_id` (`None`: out of any folder) and
/// say how many were moved. All of them are `tenant_id`'s or none moves. Moving
/// does not touch `updated_at`: that column dates a load's claim.
///
/// # Errors
///
/// [`FolderError::NotFound`] when the folder, or any one upload, is not the
/// tenant's; [`FolderError::Store`] on a database failure.
pub async fn move_uploads(
    pool: &PgPool,
    tenant_id: Uuid,
    upload_ids: &[String],
    folder_id: Option<&str>,
) -> Result<u64, FolderError> {
    let mut wanted: Vec<&str> = upload_ids.iter().map(String::as_str).collect();
    wanted.sort_unstable();
    wanted.dedup();
    if wanted.is_empty() {
        return Ok(0);
    }
    let mut tx = pool.begin().await?;
    lock_tenant(&mut tx, tenant_id).await?;
    if let Some(folder) = folder_id
        && depth_of(&mut tx, tenant_id, folder).await?.is_none()
    {
        return Err(FolderError::NotFound);
    }
    let moved =
        sqlx::query("UPDATE file_upload SET folder_id = $3 WHERE id = ANY($1) AND tenant_id = $2")
            .bind(&wanted)
            .bind(tenant_id)
            .bind(folder_id)
            .execute(&mut *tx)
            .await?;
    if usize::try_from(moved.rows_affected()).ok() != Some(wanted.len()) {
        // Dropping the transaction rolls the moves back: all or nothing.
        return Err(FolderError::NotFound);
    }
    tx.commit().await?;
    Ok(moved.rows_affected())
}

/// The folder recorded on the claim of `table` when it was last loaded, if the
/// claim is `tenant_id`'s and the folder still exists (feature page decision 2:
/// a re-upload into an existing table joins its folder).
///
/// # Errors
///
/// Returns [`StoreError::Database`] on a database failure.
pub async fn claim_folder(
    pool: &PgPool,
    tenant_id: Uuid,
    table: &str,
) -> Result<Option<String>, StoreError> {
    let folder: Option<Option<String>> = sqlx::query_scalar(
        "SELECT folder_id FROM upload_table_claim WHERE bronze_table = $1 AND tenant_id = $2",
    )
    .bind(table)
    .bind(tenant_id)
    .fetch_optional(pool)
    .await?;
    Ok(folder.flatten())
}
